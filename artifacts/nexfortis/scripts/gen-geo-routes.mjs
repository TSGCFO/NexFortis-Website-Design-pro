#!/usr/bin/env node
// Generate the geo [service]+[city] route block in src/App.tsx from the published entries
// in src/lib/geo-links.ts (the single source of truth). Literal <Route path="..."> lines so
// the prerender discovery regex finds them; one shared lazy GeoServicePage component.
//
// Usage:
//   node scripts/gen-geo-routes.mjs           # write App.tsx
//   node scripts/gen-geo-routes.mjs --check   # exit 1 if App.tsx is out of date (drift guard)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const GEO = join(root, "src/lib/geo-links.ts");
const APP = join(root, "src/App.tsx");

// Extract published entries (parentSlug + citySlug) from the GEO_PAGES literals.
const geoSrc = readFileSync(GEO, "utf8");
const re = /\{\s*parentSlug:\s*"([^"]+)"\s*,\s*citySlug:\s*"([^"]+)"[^}]*?published:\s*true[^}]*?\}/g;
const pages = [];
for (let m; (m = re.exec(geoSrc)); ) pages.push({ parentSlug: m[1], citySlug: m[2] });
pages.sort((a, b) => (a.parentSlug + a.citySlug).localeCompare(b.parentSlug + b.citySlug));

const importLine = pages.length
  ? '\nconst GeoServicePage = lazy(() => import("@/pages/services/digital-marketing/_GeoServicePageBody"));\n'
  : "\n";
const routeLines = pages.length
  ? "\n" +
    pages
      .map(
        (p) =>
          `          <Route path="/services/digital-marketing/${p.parentSlug}/${p.citySlug}">{() => <GeoServicePage service="${p.parentSlug}" city="${p.citySlug}" />}</Route>`,
      )
      .join("\n") +
    "\n          "
  : "\n          ";

const IMPORT_START = "// GEO-IMPORTS-START (generated by scripts/gen-geo-routes.mjs from src/lib/geo-links.ts — do not edit by hand)";
const ROUTE_START = "{/* GEO-ROUTES-START (generated by scripts/gen-geo-routes.mjs from src/lib/geo-links.ts — do not edit by hand) */}";

const app = readFileSync(APP, "utf8");
let out = app
  .replace(/\/\/ GEO-IMPORTS-START[\s\S]*?\/\/ GEO-IMPORTS-END/, `${IMPORT_START}${importLine}// GEO-IMPORTS-END`)
  .replace(/\{\/\* GEO-ROUTES-START[\s\S]*?GEO-ROUTES-END \*\/\}/, `${ROUTE_START}${routeLines}{/* GEO-ROUTES-END */}`);

if (process.argv.includes("--check")) {
  if (out !== app) {
    console.error("App.tsx geo route block is OUT OF DATE vs geo-links.ts — run: node scripts/gen-geo-routes.mjs");
    process.exit(1);
  }
  console.log(`geo routes in sync (${pages.length} published)`);
  process.exit(0);
}
if (out !== app) {
  writeFileSync(APP, out);
  console.log(`wrote ${pages.length} geo route(s) to App.tsx`);
} else {
  console.log(`App.tsx already up to date (${pages.length} geo route(s))`);
}
